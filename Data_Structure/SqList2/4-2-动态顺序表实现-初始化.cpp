#define _CRT_SECURE_NO_WARNINGS
#pragma once
#include "4-1-动态顺序表实现-接口函数的定义-SqList.h"

//初始化顺序表
/*
想象一下你有一排带编号的储物柜：
一开始，你只有 4 个柜子（这就是 capacity = 4）。
现在里面还没放东西（这就是 size = 0）。
如果以后东西多了，4 个柜子不够用，你可以去租更多的柜子（这就是“动态扩容”，虽然这段代码还没写扩容，但它是为以后做准备的）。
*/

void SqListInit(SqList* ps) {
	/*
	void：表示这个函数执行完不需要“还”给你什么东西（也就是返回类型为空）。
	SqListInit：函数的名字，意思是“顺序表初始化 (Init)”。
	SqList* ps：这是传入的参数。SqList 是定义的一个结构体（代表整个顺序表），* 表示这是一个指针。
	零基础重点：为什么要用指针？因为你想在函数里面修改外面的顺序表。如果不加 *，函数里修改的只是个“复印件”，
	外面的原件不会变。加了 *，就是直接拿着原件的“门牌号”去修改原件。
	*/

	assert(ps);
	/*
	ssert：断言。相当于一个“安全检查员”。
	它在检查：传进来的指针 ps 是不是 NULL（空指针）？
	如果传了个空指针进来，程序会直接报错崩溃，防止后面代码去操作不存在的内存导致更严重的错误。
	*/

	ps->arr = (SqDataType*)malloc(sizeof(SqDataType) * 4);
	/*
	这是最核心的一行，分三步看：
	sizeof(SqDataType) * 4：计算需要多大的空间。SqDataType 是你要存的数据类型（比如 int 或 char），乘以 4 表示“先给我 4 个这样的空间”。
	malloc(...)：向操作系统“租”内存。在堆区（Heap）申请一块刚才计算好的大小的连续内存。
	(SqDataType*)：类型转换。因为 malloc 默认返回的是 void*（通用指针），这里强制转换成“指向 SqDataType 的指针”。
	ps->arr = ...：把租到的这块内存的“起始地址”，存到顺序表的 arr 指针里。以后就可以通过 arr 找到这块内存了。
	*/

	if (ps->arr == NULL) {
		// 申请失败，则退出
		printf("InitSqList: 内申请空间失败!!!\n");
		//exit(-1);
		return;
	}
	/*
	申请失败的“保险”
	if (ps->arr == NULL) {
	printf("InitSqList: 内申请空间失败!!!\n");
	return;
	}
	如果系统内存满了，或者你租的空间太大，malloc 会返回 NULL（表示“租失败了”）。
	如果不检查直接用，程序就会崩溃。所以这里加个 if 判断：如果失败了，就打印一句提示，然后 return 退出函数。
	*/

	ps->size = 0;
	ps->capacity = 4;
	/*
	ps->size = 0;：当前顺序表里实际存放的数据个数是 0。（柜子刚租好，还没放东西）
	ps->capacity = 4;：当前顺序表的总容量是 4。（一共租了 4 个柜子）
	*/
}
//用一句话概括：它帮你在内存里租了 4 个连续的柜子，并记录下了柜子的地址、当前物品数（0个）和总容量（4个）。

